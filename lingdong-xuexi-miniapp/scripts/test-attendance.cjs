// 在独立小程序工程内验证纯业务模型，无需启动微信或连接服务。
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../src/pages/attendance/model.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {}, require };
vm.runInNewContext(output, sandbox);
const { attendancePermissions, attendanceToday, createAttendanceDrafts, buildAttendanceBatch } = sandbox.exports;
const allowed = { roleCodes: ['TEACHER'], permissionCodes: ['ATTENDANCE_READ', 'ATTENDANCE_RECORD'] };
assert.equal(attendancePermissions(true, allowed, 'teacher').record, true);
assert.equal(attendancePermissions(false, allowed, 'teacher').read, false);
assert.equal(attendancePermissions(true, { ...allowed, roleCodes: ['SYS_AUDITOR'] }, 'organization').read, false);
assert.equal(attendancePermissions(true, allowed, 'parent').record, false);
assert.equal(attendancePermissions(true, { ...allowed, roleCodes: ['STUDENT'] }, 'student').record, false);
assert.equal(attendanceToday(new Date('2026-09-06T16:01:00Z')), '2026-09-07');
const drafts = createAttendanceDrafts([{ studentId: '1874244142494646689', studentName: '张*', record: null }]);
assert.equal(drafts[0].selected, false);
assert.equal(drafts[0].status, '');
assert.throws(() => buildAttendanceBatch('1874244142494646690', '2026-09-07', drafts, '2026-09-07'), /1 至 100/);
drafts[0].selected = true; drafts[0].status = 'NORMAL'; drafts[0].checkinTime = '08:30';
const payload = buildAttendanceBatch('1874244142494646690', '2026-09-07', drafts, '2026-09-07');
assert.equal(payload.items[0].studentId, '1874244142494646689');
assert.equal(payload.items[0].checkinTime, '08:30:00');
assert.equal(payload.items[0].versionNo, null);
assert.throws(() => buildAttendanceBatch('1', '2026-09-08', drafts, '2026-09-07'), /未来/);
drafts[0].status = 'LEAVE';
assert.throws(() => buildAttendanceBatch('1', '2026-09-07', drafts, '2026-09-07'), /不能填写/);
drafts[0].checkinTime = ''; drafts[0].versionNo = 4;
assert.equal(buildAttendanceBatch('1', '2026-09-07', drafts, '2026-09-07').items[0].versionNo, 4);
assert.throws(() => buildAttendanceBatch('1', '2026-09-07', [drafts[0], drafts[0]], '2026-09-07'), /重复/);
console.log('小程序考勤模型：16项断言通过');
